"""Coordinator preservation and exact-artifact checks; never grants editorial approval."""
from pathlib import Path
import copy
import hashlib
import json
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
from check_chapter_standard import validate, fingerprint


def read(name):
    return json.loads((ROOT / name).read_text(encoding='utf-8-sig'))


def sha(name):
    return hashlib.sha256((ROOT / name).read_bytes()).hexdigest()


def verify(require_reviewed=False):
    before = read('output/chapter-11/before.json')
    now = read('production/p1.json')
    register = read('production/chapter-reviews.json')
    assert len(now) == len(before['lessons']) == 19
    assert len(register['chapters']) == 63
    for index, (old, current) in enumerate(zip(before['lessons'], now)):
        if index != 10:
            assert old == current, current['id']
        else:
            base = copy.deepcopy(current)
            base.pop('paired_edition', None)
            for q in base['questions']:
                q.pop('id', None)
            assert base == old
        assert [(q['prompt'], q['answer']) for q in old['questions']] == [
            (q['prompt'], q['answer']) for q in current['questions']]
    assert sum(len(x['questions']) for x in now) == 114
    assert read('production/lessons.json') == sum(
        (read(f'production/p{grade}.json') for grade in (1, 2, 3)), [])
    for name, expected in before['hashes'].items():
        assert sha(name) == expected, name
    protected = read('output/chapter-11/root-protected-files.json')
    regeneration = read('output/chapter-11/historical-export-regeneration.json')
    assert regeneration['path'] == 'Gombe-Mathematics-Book-1.pdf'
    assert regeneration['starting_sha256'] == protected[regeneration['path']]
    assert regeneration['current_sha256'] == sha(regeneration['path'])
    for name, expected in regeneration['source_checks'].items():
        assert expected == protected[name] and sha(name) == expected, name
    for name, expected in protected.items():
        if name != regeneration['path']:
            assert sha(name) == expected, name
    for old, current in zip(before['register']['chapters'][11:], register['chapters'][11:]):
        assert old == current, current['id']
    assert len(register['chapters'][11:]) == 52
    earlier_pdfs = {name for c in before['register']['chapters'][:10]
                    for name in c['artifacts'].values()}
    assert len(earlier_pdfs) == 18
    assert all(sha(name) == before['hashes'][name] for name in earlier_pdfs)
    freeze = read('output/chapter-11/author-freeze.json')
    assert freeze['hashes']
    for name, expected in freeze['hashes'].items():
        assert sha(name) == expected, name
    gates = {}
    for n in range(1, 12):
        cid = f'P1-{n:02}'
        chapter = validate(chapter_id=cid, require_reviewed=require_reviewed)[0]
        gates[cid] = fingerprint(ROOT, chapter)
    assert gates['P1-11'] == freeze['fingerprint']
    result = subprocess.run(['git', '-c', 'core.whitespace=cr-at-eol', 'diff', '--check'],
                            cwd=ROOT, capture_output=True, text=True)
    assert result.returncode == 0, result.stdout + result.stderr
    report = {
        'coordinator': '/root',
        'checks': ['114 original prompts/answers/order and 18 other complete lessons preserved',
                   'Generated lessons match all three canonical sources',
                   '18 earlier reviewed PDFs and protected original/shared sources unchanged',
                   'Ignored root historical PDF regenerated by legacy build; exact starting bytes unavailable; documented separately',
                   'Other 52 chapter records unchanged', 'Final frozen hashes match',
                   'Whitespace check passed'],
        'require_reviewed': require_reviewed,
        'historical_export_regeneration': regeneration,
        'fingerprints': gates,
        'artifacts': {role: {'path': name, 'sha256': sha(name)}
                      for role, name in register['chapters'][10]['artifacts'].items()},
        'limits': 'Continuation extracts; annual assembly, current curriculum/adoption, local trials and physical print/printer approval pending.'}
    (ROOT / 'output/chapter-11/root-validation.json').write_text(
        json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print('Coordinator preservation, frozen hashes, other 52 records and '
          + ('all eleven strict gates PASSED.' if require_reviewed else 'draft gates PASSED.'))


if __name__ == '__main__':
    verify('--require-reviewed' in sys.argv)
