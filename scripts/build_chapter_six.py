"""Build canonical P1-06 paired continuation, using isolated exact bundle renderer."""
import hashlib,json
from build_primary_one_opening import ROOT,EXPECTED_HASH,read
from build_chapter_five import BundleRenderer
from check_chapter_standard import validate
OUT=ROOT/'output/chapter-6'
FILES={r:ROOT/f'output/pdf/Maths-with-Friends-Primary-1-Numbers-to-ninety-nine-{r.title()}.pdf' for r in ('textbook','workbook')}
def build():
 assert hashlib.sha256((ROOT/'GombeTextbook.txt').read_bytes()).hexdigest()==EXPECTED_HASH
 lesson=read('production/p1.json')[5]; pair=lesson['paired_edition']
 assert lesson['id']=='P1-06' and pair['teacher_id']=='mr-aliyu'
 assert pair['source_tasks']==[dict(id=f'P1-06-Q{i}',source_prompt=q['prompt'],source_answer=q['answer']) for i,q in enumerate(lesson['questions'],1)]
 reports={}
 for role in FILES:
  reports[role]=BundleRenderer(role,pair[role+'_pages'],{'review_footer':'Chapter six / Educational review edition'},[lesson],output_dir=OUT,files=FILES,label='Numbers to ninety-nine').build()
  assert all(q['id'] in reports[role]['task_pages'] for q in pair['source_tasks'])
  ledger={x['id']:x for x in reports[role]['objects']}
  for page in pair[role+'_pages']:
   for el in page['elements']:
    if el['type']=='bundle': assert ledger[el['id']]['count']==10
  for prefix in {k.rsplit('-ten-',1)[0] if '-ten-' in k else k[:-5] for k in ledger if '-ten-' in k or k.endswith('-ones')}:
   if '-model-' in prefix:expected=int(prefix.rsplit('-',1)[1])
   elif prefix.startswith('wb-'):expected=int(prefix.split('-')[1])+2
   elif prefix=='prior-14':expected=14
   elif prefix.startswith('names'):expected=int(prefix[5:])
   else:continue
   assert sum(v['count'] for k,v in ledger.items() if k.startswith(prefix+'-'))==expected,(role,prefix)
 validate()
 before=read('output/chapter-6/before.json'); now=read('production/p1.json')
 for old,new in zip(before['lessons'],now):
  old_base={k:v for k,v in old.items() if k!='paired_edition'}
  new_base={k:v for k,v in new.items() if k!='paired_edition'}
  if new['id']=='P1-06':
   assert [q['id'] for q in new['questions']]==[f'P1-06-Q{i}' for i in range(1,7)]
   new_base['questions']=[{k:v for k,v in q.items() if k!='id'} for q in new['questions']]
  assert old_base==new_base,new['id']
 assert all(before['lessons'][i]==now[i] for i in range(19) if i!=5)
 protected_pdfs={v.replace('\\','/') for c in before['register']['chapters'][:5] for v in c['artifacts'].values()}
 assert len(protected_pdfs)==8
 matched=set()
 for original_path,sha in before['hashes'].items():
  path=original_path.replace('\\','/')
  # validate_book.py intentionally regenerates the historical sample-lessons.pdf.
  # Protect every earlier exact redesigned chapter artifact, not that generated sample.
  if path in protected_pdfs or path in ['GombeTextbook.txt','production/p2.json','production/p3.json','scripts/build_primary_one_opening.py','scripts/build_chapter_five.py','docs/CHAPTER-STANDARD.md','docs/CHAPTER-REVIEW.md','research/PRIMARY-1-ASSUMPTIONS.json']:
   assert hashlib.sha256((ROOT/path).read_bytes()).hexdigest()==sha,path
   matched.add(path)
 assert len(matched)==16,matched
 (OUT/'validation.json').write_text(json.dumps(dict(chapters=['P1-06'],artifacts={r:str(f.relative_to(ROOT)) for r,f in FILES.items()},pages={r:v['pages'] for r,v in reports.items()},source_hash=EXPECTED_HASH,checks=['all 114 original P1 prompts/answers/order and all other18 lessons unchanged','eight registered earlier chapter PDFs and eight protected source hashes unchanged; historical sample regenerated by legacy validation','each bundle ten separate vector strips; all model/count diagram totals recomputed','A4/text bounds/embedded fonts/per-page vector fill counts checked'],status='draft_pair_built_independent_review_required'),indent=2)+'\n',encoding='utf-8')
 print('Built chapter six:',{r:v['pages'] for r,v in reports.items()})
if __name__=='__main__':build()
